import { test, expect, type Locator } from '@playwright/test';
import { oeffneStartprojekt } from './projekt-einstieg';
import { existsSync, mkdirSync, readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import sharp from 'sharp';

test('Aussparung verschieben, frei verziehen, Maße, Entwurfsschutz, Undo und Reload', async ({ page }, info) => {
  test.setTimeout(120_000);
  const fehler: string[] = []; page.on('pageerror', e => fehler.push(e.message));
  const button = (name: string) => page.getByRole('button', { name, exact: true });
  const shots = resolve('.debug-shots/aussparungen-2026-10-19'); mkdirSync(shots, { recursive: true });
  const shot = async (name: string) => { expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false); await page.screenshot({ path: resolve(shots, `${info.project.name}-${name}.png`) }); };
  await page.goto('./'); await oeffneStartprojekt(page); await button('2. Dach & Belegung').click();
  const fotoPfad = process.env.PV_QA_PHOTO ?? '.debug-shots/fotoeditor-echtfoto-2026-09-30/drohnenfoto.jpg';
  const input = existsSync(fotoPfad) ? readFileSync(fotoPfad) : Buffer.from('<svg xmlns="http://www.w3.org/2000/svg" width="1600" height="900"><path fill="#8d513c" d="M0 0h1600v900H0z"/></svg>');
  const bild = await sharp(input).resize(1600, 900).jpeg().toBuffer();
  const chooser = page.waitForEvent('filechooser'); await button('Foto hinzufügen').click();
  await (await chooser).setFiles({ name: 'Dach.jpg', mimeType: 'image/jpeg', buffer: bild });
  await button('Maße & Dachform festlegen').click();
  await page.getByLabel(/^Traufe/).fill('10'); await page.getByLabel(/^Sparrenlänge/).fill('6'); await button('Maße übernehmen').click();
  await page.getByRole('button', { name: /Überspringen \(/ }).click();
  const foto = page.getByRole('img', { name: /im Foto markieren/ }); await foto.hover();
  const klick = async (x: number, y: number) => { const b = (await foto.boundingBox())!; await foto.click({ position: { x: b.width*x, y: b.height*y } }); };
  for (const [x,y] of [[.08,.88],[.92,.88],[.92,.12],[.08,.12]]) await klick(x!,y!);
  await button('4 Ecken übernehmen').click();
  await klick(.3,.4); await klick(.5,.6);
  await button('Aussparung 1 bearbeiten').click();
  await expect(page.getByTestId('aussparung-griff')).toHaveCount(4);
  const kontur = page.getByTestId('aussparung-kontur');
  const alt = await kontur.getAttribute('points');
  const ziehen = async (griff: Locator, dx: number, dy: number) => { const b = (await griff.boundingBox())!; await page.mouse.move(b.x+b.width/2,b.y+b.height/2); await page.mouse.down(); await page.mouse.move(b.x+b.width/2+dx,b.y+b.height/2+dy,{steps:6}); await page.mouse.up(); };
  await ziehen(page.getByTestId('aussparung-mitte'), 20, -10);
  await expect(kontur).not.toHaveAttribute('points', alt!);
  await expect(button('Änderungen übernehmen')).toBeEnabled(); await shot('01-verschieben');
  await button('Änderungen verwerfen').click();
  await expect(kontur).toHaveAttribute('points',alt!);
  await button('Aussparung 1 bearbeiten').click();
  await ziehen(page.getByTestId('aussparung-griff').first(), -14, 12);
  await shot('02-frei-verziehen'); await button('Änderungen übernehmen').click();
  const frei = await kontur.getAttribute('points'); expect(frei).not.toBe(alt);
  await button('Aussparung 1 bearbeiten').click();
  await page.getByLabel('Breite (m)', { exact:true }).fill('3');
  await button('Aussparung 1 cm nach rechts').click();
  await button('3. Export').click();
  await expect(page.getByRole('dialog')).toBeVisible(); await button('Bleiben').click();
  await expect(page.getByLabel('Breite (m)', {exact:true})).toHaveValue('3');
  await button('Änderungen übernehmen').click();
  const undo = page.getByRole('button', { name: /Rückgängig/ });
  await expect(undo).toBeEnabled(); await undo.click();
  await expect(kontur).toHaveAttribute('points', frei!);
  await page.getByRole('button', { name: /Wiederherstellen/ }).click();
  const gespeichert = await kontur.getAttribute('points'); expect(gespeichert).not.toBe(frei);
  await page.waitForTimeout(650); await page.reload();
  // Editor starts in the persisted setup; free contour must survive storage.
  await expect(kontur).toHaveAttribute('points', gespeichert!);
  await button('Aussparung 1 bearbeiten').click(); await shot('03-masse');
  expect(fehler).toEqual([]);
});

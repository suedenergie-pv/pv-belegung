import { expect, test } from '@playwright/test';
import { mkdirSync } from 'node:fs';
import { resolve } from 'node:path';

test('Bewusster Projekteinstieg, Fortsetzen, Reload und geschützte Browsernavigation', async ({ page }, info) => {
  test.setTimeout(90_000);
  const fehler: string[] = [];
  page.on('pageerror', (error) => fehler.push(error.message));
  const ordner = resolve('.debug-shots/navigation-2026-10-19/umsetzung');
  mkdirSync(ordner, { recursive: true });
  const shot = async (name: string) => {
    await page.evaluate(async () => {
      await document.fonts.ready;
      scrollTo(0, 0);
      await new Promise((resolve) => requestAnimationFrame(() => requestAnimationFrame(resolve)));
    });
    expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1)).toBe(false);
    await page.screenshot({ path: resolve(ordner, `${info.project.name}-${name}.png`), fullPage: true });
  };
  const button = (name: string) => page.getByRole('button', { name, exact: true });
  await page.goto('./');
  await expect(page.getByRole('heading', { name: 'Meine Projekte' })).toBeVisible();
  await expect(page.getByText('Hier beginnen deine Belegungen.')).toBeVisible();
  await shot('01-leer');
  await button('+ Neues Projekt').click();
  await expect(page.getByLabel('Kunde', { exact: true })).toBeFocused();
  await page.getByLabel('Kunde', { exact: true }).fill('Familie Muster mit langem Kundennamen');
  await page.getByLabel('Adresse', { exact: true }).fill('Musterweg 12, 88299 Leutkirch im Allgäu');
  await page.getByLabel('Erfasser (Vertrieb)').focus();
  const projektUrl = page.url();
  await shot('02-projektdaten');
  await button('2. Dach & Belegung').click();
  await button('Dachmaße').click();
  await page.getByLabel(/^Traufe/).fill('12');
  await page.getByLabel(/^Sparrenlänge/).fill('6');
  await page.goBack();
  await expect(page.getByRole('dialog')).toBeVisible();
  await expect(page).toHaveURL(projektUrl);
  await button('Bleiben').click();
  await expect(page.getByLabel(/^Traufe/)).toHaveValue('12');
  await page.goBack();
  await expect(page.getByRole('dialog')).toBeVisible();
  await button('Verwerfen').click();
  await expect(page.getByRole('heading', { name: 'Meine Projekte' })).toBeVisible();
  await expect(page).not.toHaveURL(/#\/projekt/);
  await page.goForward();
  await expect(button('2. Dach & Belegung')).toHaveAttribute('aria-current', 'step');
  if (await button('Dachmaße').getAttribute('aria-expanded') !== 'true') await button('Dachmaße').click();
  await expect(page.getByLabel(/^Traufe/)).toHaveValue('');
  await page.getByLabel(/^Traufe/).fill('14');
  await page.getByLabel(/^Sparrenlänge/).fill('7');
  await button('+ Neues Projekt').click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await button('Bleiben').click();
  await expect(page.getByLabel(/^Traufe/)).toHaveValue('14');
  await page.goBack();
  await expect(page.getByRole('dialog')).toBeVisible();
  await button('Übernehmen').click();
  await expect(page.getByRole('heading', { name: 'Meine Projekte' })).toBeVisible();
  await page.getByRole('link', { name: /Familie Muster.*Fortsetzen/ }).click();
  await expect(page.getByRole('status').filter({ hasText: 'In diesem Browser gespeichert' })).toBeVisible();
  await page.reload();
  await expect(button('2. Dach & Belegung')).toHaveAttribute('aria-current', 'step');
  await expect(page.getByText('Maße: bestätigt', { exact: true })).toBeVisible();
  await expect(button('← Alle Projekte')).toBeInViewport({ ratio: 1 });
  await expect(button('+ Neues Projekt')).toBeInViewport({ ratio: 1 });
  await shot('03-editor');
  await page.goto('./');
  await expect(page.getByRole('heading', { name: 'Meine Projekte' })).toBeVisible();
  await expect(page.getByRole('link')).toHaveCount(1);
  await button('+ Neues Projekt').click();
  await expect(page.getByLabel('Kunde', { exact: true })).toBeFocused();
  await expect(page.getByLabel('Kunde', { exact: true })).toHaveValue('');
  await page.getByLabel('Kunde', { exact: true }).fill('Familie Zweites Projekt');
  await page.getByLabel('Adresse', { exact: true }).fill('Am Sonnenhang 3, 87435 Kempten');
  await button('← Alle Projekte').click();
  await expect(page.getByRole('link')).toHaveCount(2);
  await shot('04-projekte');
  await page.getByRole('link', { name: /Familie Muster/ }).click();
  await expect(button('2. Dach & Belegung')).toHaveAttribute('aria-current', 'step');
  await button('Dachmaße').click();
  await expect(page.getByLabel(/^Traufe/)).toHaveValue('14');
  await expect(page.getByLabel(/^Sparrenlänge/)).toHaveValue('7');
  expect(fehler).toEqual([]);
});

test('Fehlender Projekt-Link führt verständlich zur Übersicht und erzeugt kein Ersatzprojekt', async ({ page }) => {
  await page.goto('./#/projekt/nicht-vorhanden');
  await expect(page.getByRole('heading', { name: 'Meine Projekte' })).toBeVisible();
  await expect(page.getByText(/Dieses Projekt ist in diesem Browser nicht vorhanden/)).toBeVisible();
  await expect(page.getByText('Hier beginnen deine Belegungen.')).toBeVisible();
  await expect(page).not.toHaveURL(/#/);
});
